"use client";

import { useState } from "react";
import { Sparkles, Crown, Image as ImageIcon, Cpu, ShieldCheck, ExternalLink } from "lucide-react";

export default function ImageStudioPage() {
  const [prompt,setPrompt]=useState("");
  const [status,setStatus]=useState("RV-1 engine not connected. Train your own checkpoint, then connect the local engine.");
  const [busy,setBusy]=useState(false);
  const [image,setImage]=useState("");
  async function generate(){
    const endpoint=process.env.NEXT_PUBLIC_RV1_ENGINE_URL;
    if(prompt.trim().length<3){setStatus("Please enter a more descriptive prompt.");return;}
    if(!endpoint){setStatus("No RV-1 engine URL configured. This studio does not fall back to an external image API.");return;}
    setBusy(true);setImage("");setStatus("Sending prompt to your RV-1 engine…");
    try{
      const response=await fetch(endpoint.replace(/\/$/,"")+"/generate",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({prompt,steps:50})});
      const data=await response.json();
      if(!response.ok) throw new Error(data.detail||"RV-1 generation failed");
      setImage(endpoint.replace(/\/$/,"")+data.file);
      setStatus("Image generated by your connected RV-1 checkpoint.");
    }catch(error){setStatus(error instanceof Error?error.message:"Could not reach the RV-1 engine.");}
    finally{setBusy(false);}
  }
  return <main className="min-h-screen bg-[#080610] text-white">
    <div className="mx-auto max-w-5xl px-4 py-6 sm:px-6">
      <header className="flex items-center justify-between gap-3 border-b border-violet-900/40 pb-5">
        <a href="/" className="text-sm text-violet-300 hover:text-white">← Anime Studio</a>
        <div className="flex items-center gap-2 text-xs tracking-[.18em] text-violet-200"><Crown size={17}/> RAPSOMETTEDY LABS</div>
      </header>
      <section className="py-10 sm:py-14">
        <div className="mb-3 inline-flex items-center gap-2 rounded-full border border-violet-500/30 bg-violet-500/10 px-3 py-1 text-xs text-violet-200"><Sparkles size={14}/> ORIGINAL MODEL • RV-1</div>
        <h1 className="max-w-3xl text-4xl font-black leading-tight sm:text-6xl">Your imagination.<br/><span className="text-violet-400">Our own AI.</span></h1>
        <p className="mt-4 max-w-2xl text-sm leading-6 text-zinc-400 sm:text-base">Rapsometeddy Vision 1 is an original image-generation research project. Anime-inspired creation first, broader visual styles next.</p>
      </section>
      <section className="grid gap-4 lg:grid-cols-[1.2fr_.8fr]">
        <div className="rounded-3xl border border-violet-900/50 bg-[#130f20] p-4 sm:p-6">
          <div className="mb-4 flex items-center gap-2 font-semibold"><ImageIcon className="text-violet-300" size={19}/> Create an image</div>
          <label htmlFor="rv1-prompt" className="mb-2 block text-xs text-zinc-400">Describe the image you want</label>
          <textarea id="rv1-prompt" value={prompt} onChange={e=>setPrompt(e.target.value)} maxLength={1000} placeholder="An original anime-inspired sky city above a violet ocean at sunset, cinematic lighting, intricate architecture…" className="min-h-36 w-full resize-y rounded-2xl border border-violet-900/60 bg-[#090711] p-4 text-sm leading-6 text-white outline-none placeholder:text-zinc-600 focus:border-violet-400"/>
          <button onClick={generate} disabled={busy} className="mt-4 flex w-full items-center justify-center gap-2 rounded-xl bg-violet-600 px-5 py-3 font-semibold transition hover:bg-violet-500 disabled:cursor-wait disabled:opacity-60"><Sparkles size={17}/>{busy?"Generating…":"Generate with RV-1"}</button>
          <p aria-live="polite" className="mt-3 min-h-10 text-xs leading-5 text-violet-200/80">{status}</p>
          {image&&<div className="mt-3 overflow-hidden rounded-2xl border border-violet-800"><img src={image} alt="Generated by Rapsometeddy Vision 1" className="h-auto w-full"/><a href={image} download className="block p-3 text-center text-sm text-violet-200">Open / save image</a></div>}
        </div>
        <aside className="space-y-4">
          <div className="rounded-3xl border border-violet-900/50 bg-[#130f20] p-5">
            <div className="mb-3 flex items-center gap-2 font-semibold"><Cpu className="text-violet-300" size={18}/> RV-1 model status</div>
            <div className="rounded-xl bg-black/30 p-3"><div className="text-xs text-zinc-500">MODEL CHECKPOINT</div><div className="mt-1 text-sm">Not connected</div></div>
            <p className="mt-3 text-xs leading-5 text-zinc-400">The model must be trained from random initialization before image generation becomes available.</p>
          </div>
          <div className="rounded-3xl border border-violet-900/50 bg-[#130f20] p-5">
            <div className="mb-3 flex items-center gap-2 font-semibold"><ShieldCheck className="text-violet-300" size={18}/> Independence rules</div>
            <ul className="space-y-2 text-xs leading-5 text-zinc-400"><li>✓ No paid image APIs</li><li>✓ No pretrained image-generation weights</li><li>✓ Own model architecture and training</li><li>✓ Licensed / permission-based training data</li></ul>
          </div>
          <a href="https://github.com/Rapsometeddy/Rapsometeddy-Anime-Studio/tree/main/rv1" target="_blank" rel="noreferrer" className="flex items-center justify-between rounded-2xl border border-violet-900/50 p-4 text-sm text-violet-200 hover:bg-violet-950/40">RV-1 training source <ExternalLink size={15}/></a>
        </aside>
      </section>
      <footer className="py-8 text-center text-[11px] text-zinc-600">RAPSOMETTEDY VISION 1 • RESEARCH PREVIEW • MODEL TRAINING NOT YET COMPLETE</footer>
    </div>
  </main>;
}
